"""
Synthetic diagram generation module.

Generates three flavours of synthetic Mermaid diagrams:
  meaningful            — realistic-looking fictional flowcharts/architecture diagrams
  nonsense_chaos        — internally self-consistent but unmappable to any real-world domain
  nonsense_misleading   — real-world scenarios with counter-intuitive alterations

For each sample the module saves:
  dataset/meaningful_<NNN>/diagram.mmd   + diagram.png
  dataset/nonsense_chaos_<NNN>/diagram.mmd   + diagram.png
  dataset/nonsense_misleading_<NNN>/diagram.mmd   + diagram.png

And updates dataset/synthetic_metadata.json incrementally.

(Descriptions and QA are generated by describe.py / qa.py in separate steps.)

Resumable: already-present sample IDs in synthetic_metadata.json are skipped.

Usage (via main.py):
  python main.py synth [--type meaningful|chaos|misleading|all] [--count N] [--start-index N]
"""
from __future__ import annotations

import hashlib
import json
import random
import re
import time
from pathlib import Path

import env_config
from flowsight.config import (
    DATASET_DIR,
    SYNTH_METADATA,
    SYNTH_LOG,
    SYNTH_MEANINGFUL,
    SYNTH_CHAOS,
    SYNTH_MISLEADING,
    MEANINGFUL_THEMES,
    REAL_METADATA,
)
from flowsight.utils import (
    log as _log,
    load_json,
    save_json,
    render_png,
    openrouter_chat,
    now_ts,
)

MAX_RETRIES = 12   # keep retrying until PNG render succeeds (mermaid.ink can be flaky)
RETRY_SLEEP = 5

_meta_lock = __import__("threading").Lock()


def log(msg: str) -> None:
    _log(msg, SYNTH_LOG)


# ── Mermaid source hash for dedup ─────────────────────────────────────────────

def _hash_mmd(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()[:16]


# ── LLM call wrapper ─────────────────────────────────────────────────────────

def _chat(messages: list, api_key: str, model: str, max_tokens: int = 1_200) -> str | None:
    return openrouter_chat(messages, api_key=api_key, model=model,
                           max_tokens=max_tokens, temperature=0.9,
                           _log_file=SYNTH_LOG)


# ── Extract mermaid block from LLM response ───────────────────────────────────

def extract_mermaid_block(text: str) -> str | None:
    m = re.search(r"```mermaid\s*\n([\s\S]+?)\n\s*```", text, re.IGNORECASE)
    if m:
        return m.group(1).strip()
    return None


def extract_introduced_errors(raw: str) -> list[str]:
    """Extract the deliberately introduced counterfactual error list from a misleading response."""
    m = re.search(r"##\s*Introduced Counterfactual Errors?\s*\n([\s\S]*?)(?:\n##|\Z)", raw)
    if not m:
        return []
    lines = m.group(1).strip().splitlines()
    return [l.lstrip("- ").strip() for l in lines if l.strip()]


# ── Real mermaid-line distribution for complexity matching ────────────────────

def _load_real_line_distribution() -> list[int]:
    data = load_json(REAL_METADATA, default=[])
    lines = [int(item.get("mermaid_lines", 20)) for item in data
             if isinstance(item.get("mermaid_lines"), (int, float))]
    return lines if lines else [15, 20, 25, 30, 22, 18, 35, 10, 40, 50] * 10


def _build_target_lines(total: int) -> list[int]:
    dist = _load_real_line_distribution()
    rng = random.Random(2025)
    return [rng.choice(dist) for _ in range(total)]


# ── Prompt builders ───────────────────────────────────────────────────────────

def _prompt_meaningful(theme: str, n: int) -> str:
    return (
        "Generate a Mermaid flowchart or architecture diagram (graph TD or flowchart TD/LR).\n\n"
        "Requirements:\n"
        "1. Completely fictional — do NOT copy any real project. "
        "Use realistic technical/business terminology as found in real engineering documentation.\n"
        f"2. **Topic/domain for this diagram: {theme}**. "
        "Choose a specific scenario within this domain (concrete module names, step names, "
        "component labels); avoid generic textbook examples.\n"
        f"3. Approximately {n} lines (nodes + edges + optional classDef). "
        "Structure must be clear and non-trivial; may include branches, convergence, "
        "and multi-step chains.\n"
        "4. Output ONE Mermaid code block only — no other text before or after. "
        "Syntax must be valid and renderable by mermaid.ink.\n"
        "5. Use **English** for all node labels and edge condition text."
    )


def _prompt_chaos(n: int, diversity_hint: str) -> str:
    return (
        "Generate a Mermaid flowchart (graph TD or flowchart TD) that depicts a "
        "**fictional system process**.\n\n"
        "The diagram must be **structurally identical** to a real engineering or business "
        "flowchart — proper branching, convergence, decision diamonds, sequential steps, "
        "typed edges, clear start/end.\n\n"
        "**The single key constraint**: every domain term (node labels, edge labels, component "
        "names) must be **invented**. Use professional-sounding compound nouns and product-style "
        "names that do NOT correspond to any real technology, product, standard, or concept.\n\n"
        "Good examples: 'CoreSync Validation', 'FluxBridge Router', 'VaultNode Handshake', "
        "'ArcLane Distributor', 'SpectraQueue Flush', 'ZenithGate Auth Layer'.\n\n"
        "Bad examples: 'Quantum Banana Arbitration' (too absurd — looks like a joke, not a "
        "system), 'XYZ123' (random string), 'database' / 'API' / 'user' (real terms).\n\n"
        "The result should look like it came from a real company's internal docs for a product "
        "that happens not to exist. A reader should need the diagram to answer any question "
        "about the process — no prior knowledge helps.\n\n"
        f"~{n} lines. Valid Mermaid syntax renderable by mermaid.ink. "
        "One code block only — no other text. All labels in **English**.\n"
        f"{diversity_hint}"
    )


def _prompt_misleading(n: int, diversity_hint: str) -> str:
    return (
        "Generate a Mermaid flowchart (graph TD or flowchart TD) for a common real-world "
        "process (e.g. order processing, CI/CD, data pipeline, user onboarding, incident "
        "response — vary across generations).\n\n"
        "**First**, design a correct version of the flowchart in your mind — the same kind "
        "of diagram you would produce for the 'meaningful' category.\n\n"
        "**Then**, introduce **5–8 subtle counter-factual alterations** so that the flow "
        "logic no longer matches what common sense would predict. The alterations should be "
        "hard to spot on a quick skim but identifiable by carefully tracing the arrows.\n\n"
        "Alteration types (use a mix):\n"
        "- Reversed sequence (step A shown after step B, should be before)\n"
        "- Swapped branch outcomes (Yes/No transposed)\n"
        "- Wrong causal direction (effect before cause)\n"
        "- Contradictory edge label (e.g. 'success' leading to error path)\n"
        "- Illogical loop (completion feeds back into early stage)\n"
        "- Skipped critical step\n"
        "- Wrong merge of parallel paths\n\n"
        f"~{n} lines. Valid Mermaid syntax. All labels in **English**.\n\n"
        "**Output** (two parts):\n"
        "1. A Mermaid code block.\n"
        "2. '## Introduced Counterfactual Errors' — bullet list, format: "
        "`- [ErrorType] description (shown vs expected)`\n"
        f"{diversity_hint}"
    )


# ── Per-type generation ───────────────────────────────────────────────────────

def _diversity_hint(local_idx: int, subtype: str) -> str:
    if local_idx % 20 == 0:
        return "(Make this diagram structurally very different from the previous ones.)"
    return ""


def generate_mmd_meaningful(
    target_lines: int, local_idx: int, api_key: str, model: str
) -> str | None:
    theme = MEANINGFUL_THEMES[local_idx % len(MEANINGFUL_THEMES)]
    prompt = _prompt_meaningful(theme, target_lines)
    resp = _chat([{"role": "user", "content": prompt}], api_key, model, max_tokens=1_400)
    if not resp:
        return None
    return extract_mermaid_block(resp)


def generate_mmd_nonsense(
    subtype: str, target_lines: int, local_idx: int, api_key: str, model: str
) -> tuple[str | None, list[str]]:
    """Returns (mmd_code, introduced_errors). introduced_errors is non-empty only for misleading."""
    hint = _diversity_hint(local_idx, subtype)
    if subtype == "chaos":
        prompt = _prompt_chaos(target_lines, hint)
        resp = _chat([{"role": "user", "content": prompt}], api_key, model, max_tokens=1_200)
        if not resp:
            return None, []
        mmd = extract_mermaid_block(resp)
        return mmd, []
    else:  # misleading
        prompt = _prompt_misleading(target_lines, hint)
        resp = _chat([{"role": "user", "content": prompt}], api_key, model, max_tokens=1_600)
        if not resp:
            return None, []
        mmd = extract_mermaid_block(resp)
        errors = extract_introduced_errors(resp)
        return mmd, errors


# ── Single-sample generation with retry ──────────────────────────────────────

def _try_generate_one(
    prefix: str,
    local_idx: int,
    subtype: "str | None",
    target_lines: int,
    seen_hashes: "set[str]",
    api_key: str,
    model: str,
    seen_hashes_lock: "object | None" = None,
) -> "dict | None":
    """
    prefix: 'meaningful' | 'nonsense_chaos' | 'nonsense_misleading'
    subtype: None (meaningful), 'chaos', or 'misleading'
    """
    def _check_add_hash(h: str) -> bool:
        if seen_hashes_lock is not None:
            with seen_hashes_lock:
                if h in seen_hashes:
                    return True
                seen_hashes.add(h)
                return False
        if h in seen_hashes:
            return True
        seen_hashes.add(h)
        return False

    sample_id = f"{prefix}_{local_idx:03d}"
    entry_dir = DATASET_DIR / sample_id
    entry_dir.mkdir(parents=True, exist_ok=True)

    for attempt in range(MAX_RETRIES):
        try:
            if prefix == "meaningful":
                mmd = generate_mmd_meaningful(target_lines, local_idx, api_key, model)
                introduced_errors: list[str] = []
            else:
                mmd, introduced_errors = generate_mmd_nonsense(
                    subtype or "chaos", target_lines, local_idx, api_key, model
                )

            if not mmd or len(mmd.strip()) < 20:
                log(f"    [{sample_id}] attempt {attempt+1}: empty/short mmd — retrying")
                time.sleep(RETRY_SLEEP)
                continue

            mmd_hash = _hash_mmd(mmd)
            if _check_add_hash(mmd_hash):
                log(f"    [{sample_id}] attempt {attempt+1}: duplicate mmd — retrying")
                time.sleep(RETRY_SLEEP)
                continue

            png_path = entry_dir / "diagram.png"
            if not render_png(mmd, png_path):
                log(f"    [{sample_id}] attempt {attempt+1}: PNG render failed — retrying")
                time.sleep(RETRY_SLEEP)
                continue

            (entry_dir / "diagram.mmd").write_text(mmd, encoding="utf-8")

            meta: dict = {
                "id": sample_id,
                "source": "synthetic_realistic" if prefix == "meaningful" else "synthetic_nonsense",
                "mermaid_lines": len(mmd.splitlines()),
                "files": {
                    "mermaid": f"dataset/{sample_id}/diagram.mmd",
                    "png": f"dataset/{sample_id}/diagram.png",
                    "description": f"dataset/{sample_id}/description.txt",
                    "qa": f"dataset/{sample_id}/qa.json",
                },
            }
            if subtype:
                meta["nonsense_subtype"] = subtype
            if introduced_errors:
                meta["introduced_errors"] = introduced_errors

            log(f"    [{sample_id}] OK (lines={meta['mermaid_lines']}, errors={len(introduced_errors)})")
            return meta

        except Exception as e:
            log(f"    [{sample_id}] attempt {attempt+1} error: {e}")
            time.sleep(RETRY_SLEEP * (attempt + 1))

    log(f"    [{sample_id}] FAILED after {MAX_RETRIES} attempts — skipping")
    try:
        if entry_dir.exists() and not any(entry_dir.iterdir()):
            entry_dir.rmdir()
    except Exception:
        pass
    return None


# ── Incremental metadata append ───────────────────────────────────────────────

def _append_meta(meta: dict) -> None:
    with _meta_lock:
        existing: list = load_json(SYNTH_METADATA, default=[])
        existing.append(meta)
        save_json(SYNTH_METADATA, existing)


# ── Public run interface ──────────────────────────────────────────────────────

def run(
    synth_type: str = "all",
    count: int | None = None,
    start_index: int = 0,
    workers: int = 5,
) -> None:
    """
    Generate synthetic diagrams (parallel with ThreadPoolExecutor).

    synth_type: 'meaningful' | 'chaos' | 'misleading' | 'all'
    count:      override default count for the selected type(s)
    start_index: resume from this index within the type's range
    workers:    number of parallel threads (default 5)
    """
    import threading
    from concurrent.futures import ThreadPoolExecutor, as_completed

    api_key = env_config.get_openrouter_api_key()
    model = env_config.get_generation_model()
    if not api_key:
        log("ERROR: OPENROUTER_API_KEY not set — aborting synth.")
        return

    existing_meta: list = load_json(SYNTH_METADATA, default=[])
    done_ids: set[str] = {m["id"] for m in existing_meta}
    seen_hashes: set[str] = set()
    seen_hashes_lock = threading.Lock()

    total_needed = SYNTH_MEANINGFUL + SYNTH_CHAOS + SYNTH_MISLEADING
    target_lines_all = _build_target_lines(total_needed)

    # Build work groups: (prefix, local_idx, subtype, target_lines_global_idx)
    groups: list[tuple[str, int, str | None, int]] = []
    g_idx = 0
    if synth_type in ("meaningful", "all"):
        n = count if count is not None else SYNTH_MEANINGFUL
        for i in range(start_index, n):
            groups.append(("meaningful", i, None, g_idx))
            g_idx += 1
    if synth_type in ("chaos", "all"):
        n = count if count is not None else SYNTH_CHAOS
        for i in range(start_index, n):
            groups.append(("nonsense_chaos", i, "chaos", g_idx))
            g_idx += 1
    if synth_type in ("misleading", "all"):
        n = count if count is not None else SYNTH_MISLEADING
        for i in range(start_index, n):
            groups.append(("nonsense_misleading", i, "misleading", g_idx))
            g_idx += 1

    pending = [
        (prefix, local_idx, subtype, tl_idx)
        for prefix, local_idx, subtype, tl_idx in groups
        if f"{prefix}_{local_idx:03d}" not in done_ids
    ]
    effective_workers = min(workers, len(pending)) if pending else 1

    log(f"[synth] type={synth_type} pending={len(pending)} already_done={len(done_ids)} workers={effective_workers}")

    generated = 0

    def _task(prefix: str, local_idx: int, subtype: "str | None", tl_idx: int) -> "dict | None":
        tl = target_lines_all[tl_idx % len(target_lines_all)]
        log(f"  generating {prefix}_{local_idx:03d} (type={subtype or prefix}, ~{tl} lines) …")
        return _try_generate_one(
            prefix=prefix,
            local_idx=local_idx,
            subtype=subtype,
            target_lines=tl,
            seen_hashes=seen_hashes,
            seen_hashes_lock=seen_hashes_lock,
            api_key=api_key,
            model=model,
        )

    with ThreadPoolExecutor(max_workers=effective_workers) as executor:
        future_to_id = {
            executor.submit(_task, prefix, local_idx, subtype, tl_idx): f"{prefix}_{local_idx:03d}"
            for prefix, local_idx, subtype, tl_idx in pending
        }
        for future in as_completed(future_to_id):
            sample_id = future_to_id[future]
            try:
                meta = future.result()
            except Exception as exc:
                log(f"  [{sample_id}] thread exception: {exc}")
                meta = None
            if meta:
                _append_meta(meta)
                done_ids.add(sample_id)
                generated += 1

    total_done = len(load_json(SYNTH_METADATA, default=[]))
    log(f"\n[synth done] generated={generated} this run, total_in_metadata={total_done}")
